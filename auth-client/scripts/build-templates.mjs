/**
 * Generates the files `npx auth-client init` copies into a consuming project.
 *
 * The ejected screens are DERIVED from src/ui/ rather than hand-maintained, so
 * a change to a library screen can never silently drift from the copy a team
 * gets. The only transformation is rewriting the library's internal relative
 * imports to the package's public entry point.
 *
 *   node scripts/build-templates.mjs
 */

import { readFileSync, writeFileSync, mkdirSync, rmSync, cpSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const PKG = JSON.parse(readFileSync(join(ROOT, 'package.json'), 'utf8')).name
/** Hand-written templates (config, barrel, .env block) — copied verbatim. */
const STATIC = join(ROOT, 'templates')
/** Build output. Lives under dist/ so it is obviously generated, and is
 *  already covered by the existing `dist` ignore rule. */
const OUT = join(ROOT, 'dist/templates')

const SCREENS = [
  'SignIn', 'SignUp', 'OtpVerify', 'ForgotPassword',
  'ResetPassword', 'ChangePassword', 'DeleteAccount',
]

/** Splits `{ a, b }` / `Default` / `Default, { a }` into the names it binds. */
function bindingsOf(clause) {
  const named = clause.match(/\{([^}]*)\}/)?.[1] ?? ''
  const defaultName = clause.replace(/\{[^}]*\}/, '').replace(/,/g, '').trim()

  const names = named.split(',').map((n) => n.trim()).filter(Boolean)
  // A default import of a library component is a *named* export on the barrel:
  // `import AuthCard from '../components/AuthCard'` -> `import { AuthCard }`.
  if (defaultName) names.unshift(defaultName)
  return names
}

/**
 * @param {string} source
 * @param {(specifier: string) => boolean} keepRelative paths to leave alone
 */
function rewriteImports(source, keepRelative = () => false) {
  const fromPackage = new Set()
  const kept = []

  const withoutLibImports = source.replace(
    /^import\s+([^;]+?)\s+from\s+'([^']+)'\n/gm,
    (match, clause, specifier) => {
      // Third-party (react, etc.) stays exactly as written.
      if (!specifier.startsWith('.')) return match
      if (keepRelative(specifier)) {
        kept.push(match.trimEnd())
        return ''
      }
      bindingsOf(clause).forEach((name) => fromPackage.add(name))
      return ''
    }
  )

  const packageImport = fromPackage.size
    ? `import {\n${[...fromPackage].sort().map((n) => `  ${n},`).join('\n')}\n} from '${PKG}'\n`
    : ''

  // Re-attach the imports we preserved, then the single package import.
  return (withoutLibImports.replace(
    /^(import[^;]+?from\s+'[^']+'\n)(?!import)/m,
    `$1${packageImport}${kept.length ? kept.join('\n') + '\n' : ''}`
  ))
}

function banner(name) {
  return `/**
 * ${name} — generated by \`npx auth-client init\`.
 *
 * This file belongs to YOUR project. Edit it freely: change the copy, the
 * layout, swap the primitives for your own design system, or delete it and
 * write your own. It will not be overwritten by a package upgrade, and you
 * never need to fork ${PKG} to change how auth looks.
 */
`
}

// Always regenerated: templates/ copied verbatim, plus src/ui/ transformed.
rmSync(OUT, { recursive: true, force: true })
// templates/auth -> the folder scaffolded into the project
// templates/app  -> optional wiring for main.jsx / App.jsx
// templates/env  -> the block merged into .env
mkdirSync(join(OUT, 'auth', 'screens'), { recursive: true })
cpSync(STATIC, OUT, { recursive: true })

// --- screens ---------------------------------------------------------------
for (const screen of SCREENS) {
  const source = readFileSync(join(ROOT, 'src/ui/screens', `${screen}.jsx`), 'utf8')
  writeFileSync(join(OUT, 'auth', 'screens', `${screen}.jsx`), banner(screen) + rewriteImports(source))
}

// --- AuthFlow: keep ./screens/* relative so it drives the ejected copies ----
const authFlow = readFileSync(join(ROOT, 'src/ui/AuthFlow.jsx'), 'utf8')
writeFileSync(
  join(OUT, 'auth', 'AuthFlow.jsx'),
  banner('AuthFlow') + rewriteImports(authFlow, (s) => s.startsWith('./screens/'))
)

console.log(`dist/templates rebuilt: ${SCREENS.length} screens + AuthFlow + auth/app/env templates`)
